-- CU010 Registrar y autenticar usuario --------------------------------------
CREATE FUNCTION fn_registrar_usuario(p_nombre varchar, p_email varchar, p_clave text, p_rol varchar)
RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_id integer;
BEGIN
    IF length(p_clave) < 8 THEN
        RAISE EXCEPTION 'La contraseña debe tener al menos 8 caracteres.';
    END IF;
    INSERT INTO usuario (nombre, email, password_hash, rol_id)
    VALUES (trim(p_nombre), lower(trim(p_email)), crypt(p_clave, gen_salt('bf', 10)),
            (SELECT id FROM rol WHERE codigo = p_rol))
    RETURNING id INTO v_id;
    RETURN v_id;
END;
$$;

-- Devuelve el usuario y su rol si las credenciales son válidas; bloquea 15 min tras 5 intentos
CREATE FUNCTION fn_autenticar(p_email varchar, p_clave text, p_ip inet DEFAULT NULL)
RETURNS TABLE (usuario_id integer, nombre varchar, rol varchar)
LANGUAGE plpgsql AS $$
DECLARE
    u usuario%ROWTYPE;
BEGIN
    SELECT * INTO u FROM usuario WHERE lower(email) = lower(trim(p_email));

    IF NOT FOUND OR NOT u.activo OR (u.bloqueado_hasta IS NOT NULL AND u.bloqueado_hasta > now())
       OR u.password_hash <> crypt(p_clave, u.password_hash) THEN
        INSERT INTO bitacora_acceso (usuario_id, email, exitoso, ip) VALUES (u.id, p_email, false, p_ip);
        IF u.id IS NOT NULL THEN
            UPDATE usuario
               SET intentos_fallidos = intentos_fallidos + 1,
                   bloqueado_hasta = CASE WHEN intentos_fallidos + 1 >= 5 THEN now() + interval '15 minutes' END
             WHERE id = u.id;
        END IF;
        RETURN;
    END IF;

    UPDATE usuario SET intentos_fallidos = 0, bloqueado_hasta = NULL, ultimo_acceso = now() WHERE id = u.id;
    INSERT INTO bitacora_acceso (usuario_id, email, exitoso, ip) VALUES (u.id, p_email, true, p_ip);

    RETURN QUERY SELECT u.id, u.nombre, r.codigo FROM rol r WHERE r.id = u.rol_id;
END;
$$;

-- CU015 Verificación de permisos por rol -------------------------------------
CREATE FUNCTION fn_tiene_permiso(p_usuario_id integer, p_permiso varchar) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
          FROM usuario u
          JOIN rol_permiso rp ON rp.rol_id = u.rol_id
          JOIN permiso p      ON p.id = rp.permiso_id
         WHERE u.id = p_usuario_id AND u.activo AND p.codigo = p_permiso
    );
$$;

-- CU030 Publicar catálogo de campaña ------------------------------------------
CREATE FUNCTION fn_publicar_campana(p_campana_id smallint) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM catalogo_item WHERE campana_id = p_campana_id) THEN
        RAISE EXCEPTION 'La campaña no tiene productos en su catálogo.';
    END IF;
    UPDATE campana SET estado = 'CERRADA', cerrada_en = now()
     WHERE estado = 'PUBLICADA' AND id <> p_campana_id;
    UPDATE campana SET estado = 'PUBLICADA', publicada_en = now()
     WHERE id = p_campana_id AND estado = 'BORRADOR';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Solo se puede publicar una campaña en preparación.';
    END IF;
END;
$$;

-- Copia los productos activos al catálogo de una campaña nueva (precio base, sin oferta)
CREATE FUNCTION fn_armar_catalogo(p_campana_id smallint) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_filas integer;
BEGIN
    INSERT INTO catalogo_item (campana_id, producto_id, pagina, precio)
    SELECT p_campana_id, p.id,
           4 + (row_number() OVER (ORDER BY p.categoria_id, p.id) - 1) * 2
             - ((row_number() OVER (ORDER BY p.categoria_id, p.id) - 1) % 2),
           p.precio_base
      FROM producto p
     WHERE p.activo
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_filas = ROW_COUNT;
    RETURN v_filas;
END;
$$;

-- CU040 Registrar pedido en el carrito ----------------------------------------
CREATE FUNCTION fn_agregar_al_carrito(p_vendedora_id integer, p_producto_id integer, p_cantidad integer)
RETURNS integer   -- id del pedido en borrador
LANGUAGE plpgsql AS $$
DECLARE
    v_campana  smallint;
    v_pedido   integer;
    v_precio   numeric(12,2);
BEGIN
    SELECT id INTO v_campana FROM campana WHERE estado = 'PUBLICADA';
    IF v_campana IS NULL THEN
        RAISE EXCEPTION 'No hay una campaña publicada.';
    END IF;
    IF (SELECT estado FROM vendedora WHERE id = p_vendedora_id) <> 'ACTIVA' THEN
        RAISE EXCEPTION 'La vendedora no está activa.';
    END IF;

    SELECT COALESCE(precio_oferta, precio) INTO v_precio
      FROM catalogo_item WHERE campana_id = v_campana AND producto_id = p_producto_id;
    IF v_precio IS NULL THEN
        RAISE EXCEPTION 'El producto no está en el catálogo vigente.';
    END IF;

    SELECT id INTO v_pedido FROM pedido
     WHERE vendedora_id = p_vendedora_id AND campana_id = v_campana AND estado = 'BORRADOR';
    IF v_pedido IS NULL THEN
        INSERT INTO pedido (numero, campana_id, vendedora_id)
        VALUES (fn_numero_pedido(), v_campana, p_vendedora_id)
        RETURNING id INTO v_pedido;
    END IF;

    IF p_cantidad <= 0 THEN
        DELETE FROM pedido_detalle WHERE pedido_id = v_pedido AND producto_id = p_producto_id;
    ELSE
        INSERT INTO pedido_detalle (pedido_id, producto_id, cantidad, precio_unitario)
        VALUES (v_pedido, p_producto_id, p_cantidad, v_precio)
        ON CONFLICT (pedido_id, producto_id) DO UPDATE SET cantidad = EXCLUDED.cantidad, precio_unitario = EXCLUDED.precio_unitario;
    END IF;
    RETURN v_pedido;
END;
$$;

-- CU045 Confirmar y enviar pedido: valida existencias y las reserva ------------
CREATE FUNCTION fn_enviar_pedido(p_pedido_id integer, p_cliente_id integer DEFAULT NULL) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    r record;
BEGIN
    PERFORM 1 FROM pedido WHERE id = p_pedido_id AND estado = 'BORRADOR' FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Solo se puede enviar un pedido en borrador.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pedido_detalle WHERE pedido_id = p_pedido_id) THEN
        RAISE EXCEPTION 'El pedido no tiene productos.';
    END IF;

    FOR r IN
        SELECT d.producto_id, d.cantidad, i.existencia - i.reservado AS disponible, p.nombre
          FROM pedido_detalle d
          JOIN inventario i ON i.producto_id = d.producto_id
          JOIN producto p   ON p.id = d.producto_id
         WHERE d.pedido_id = p_pedido_id
         FOR UPDATE OF i
    LOOP
        IF r.cantidad > r.disponible THEN
            RAISE EXCEPTION 'No hay existencia suficiente de "%": pediste %, hay % disponibles.', r.nombre, r.cantidad, r.disponible;
        END IF;
        UPDATE inventario SET reservado = reservado + r.cantidad WHERE producto_id = r.producto_id;
        INSERT INTO movimiento_inventario (producto_id, tipo, cantidad, referencia, pedido_id, usuario_id)
        VALUES (r.producto_id, 'RESERVA', r.cantidad, 'Pedido ' || (SELECT numero FROM pedido WHERE id = p_pedido_id), p_pedido_id, fn_usuario_actual());
    END LOOP;

    UPDATE pedido
       SET estado = 'ENVIADO', enviado_en = now(), cliente_id = COALESCE(p_cliente_id, cliente_id)
     WHERE id = p_pedido_id;
END;
$$;

-- CU075 Facturar pedido -------------------------------------------------------
CREATE FUNCTION fn_facturar_pedido(p_pedido_id integer) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    p pedido%ROWTYPE;
    v_factura integer;
BEGIN
    SELECT * INTO p FROM pedido WHERE id = p_pedido_id FOR UPDATE;
    IF p.estado IS DISTINCT FROM 'ENVIADO' THEN
        RAISE EXCEPTION 'Solo se facturan pedidos enviados (estado actual: %).', p.estado;
    END IF;
    INSERT INTO factura (numero, pedido_id, subtotal, tasa_itbis, itbis, total, emitida_por)
    VALUES (replace(p.numero, 'PED', 'FAC'), p.id, p.subtotal, fn_tasa_itbis(), p.itbis, p.total, fn_usuario_actual())
    RETURNING id INTO v_factura;
    UPDATE pedido SET estado = 'FACTURADO' WHERE id = p.id;
    RETURN v_factura;
END;
$$;

-- CU080 Despachar: la mercancía reservada sale del almacén ---------------------
CREATE FUNCTION fn_despachar_pedido(p_pedido_id integer, p_mensajero varchar) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    p pedido%ROWTYPE;
    v_despacho integer;
BEGIN
    SELECT * INTO p FROM pedido WHERE id = p_pedido_id FOR UPDATE;
    IF p.estado IS DISTINCT FROM 'FACTURADO' THEN
        RAISE EXCEPTION 'Solo se despachan pedidos facturados (estado actual: %).', p.estado;
    END IF;

    UPDATE inventario i
       SET existencia = i.existencia - d.cantidad,
           reservado  = i.reservado  - d.cantidad
      FROM pedido_detalle d
     WHERE d.pedido_id = p.id AND i.producto_id = d.producto_id;

    INSERT INTO movimiento_inventario (producto_id, tipo, cantidad, referencia, pedido_id, usuario_id)
    SELECT d.producto_id, 'SALIDA', d.cantidad, 'Despacho ' || p.numero, p.id, fn_usuario_actual()
      FROM pedido_detalle d WHERE d.pedido_id = p.id;

    INSERT INTO despacho (pedido_id, mensajero, guia)
    VALUES (p.id, p_mensajero, 'GD-' || (5000 + right(p.numero, 6)::int))
    RETURNING id INTO v_despacho;

    UPDATE pedido SET estado = 'EN_DESPACHO' WHERE id = p.id;
    RETURN v_despacho;
END;
$$;

