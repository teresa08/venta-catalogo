END;
$$;

-- Cancelación: libera las reservas y anula la factura si existía
CREATE FUNCTION fn_cancelar_pedido(p_pedido_id integer, p_motivo varchar) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    p pedido%ROWTYPE;
BEGIN
    SELECT * INTO p FROM pedido WHERE id = p_pedido_id FOR UPDATE;
    IF p.estado NOT IN ('BORRADOR', 'ENVIADO', 'FACTURADO') THEN
        RAISE EXCEPTION 'Un pedido % ya no se puede cancelar.', lower(p.estado);
    END IF;

    IF p.estado IN ('ENVIADO', 'FACTURADO') THEN
        UPDATE inventario i SET reservado = i.reservado - d.cantidad
          FROM pedido_detalle d
         WHERE d.pedido_id = p.id AND i.producto_id = d.producto_id;
        INSERT INTO movimiento_inventario (producto_id, tipo, cantidad, referencia, pedido_id, usuario_id)
        SELECT d.producto_id, 'LIBERACION', d.cantidad, 'Cancelación ' || p.numero, p.id, fn_usuario_actual()
          FROM pedido_detalle d WHERE d.pedido_id = p.id;
    END IF;

    UPDATE factura SET estado = 'ANULADA', anulada_en = now(), motivo_anulacion = p_motivo
     WHERE pedido_id = p.id AND estado = 'EMITIDA';

    PERFORM set_config('app.nota', p_motivo, true);
    UPDATE pedido SET estado = 'CANCELADO' WHERE id = p.id;
    PERFORM set_config('app.nota', '', true);
END;
$$;

-- CU070 Controlar existencias: entradas de mercancía y ajustes por conteo ------
CREATE FUNCTION fn_registrar_movimiento(p_producto_id integer, p_tipo varchar, p_cantidad integer, p_referencia varchar)
RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
    v_id bigint;
BEGIN
    IF p_tipo NOT IN ('ENTRADA', 'AJUSTE') THEN
        RAISE EXCEPTION 'Use ENTRADA o AJUSTE; las reservas y salidas las generan los pedidos.';
    END IF;
    IF p_tipo = 'ENTRADA' AND p_cantidad <= 0 THEN
        RAISE EXCEPTION 'Una entrada debe tener cantidad positiva.';
    END IF;

    UPDATE inventario SET existencia = existencia + p_cantidad WHERE producto_id = p_producto_id;
    INSERT INTO movimiento_inventario (producto_id, tipo, cantidad, referencia, usuario_id)
    VALUES (p_producto_id, p_tipo, p_cantidad, p_referencia, fn_usuario_actual())
    RETURNING id INTO v_id;
    RETURN v_id;
END;
$$;

-- CU060 Calcular comisiones de la campaña --------------------------------------
-- Ventas = subtotal sin ITBIS de los pedidos no cancelados (y no borradores) de la campaña.
CREATE FUNCTION fn_calcular_comisiones(p_campana_id smallint) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_filas integer;
BEGIN
    IF EXISTS (SELECT 1 FROM comision WHERE campana_id = p_campana_id AND estado <> 'CALCULADA') THEN
        RAISE EXCEPTION 'La liquidación de esta campaña ya fue aprobada; no se puede recalcular.';
    END IF;

    DELETE FROM comision WHERE campana_id = p_campana_id;

    INSERT INTO comision (vendedora_id, campana_id, nivel_id, monto_ventas, porcentaje, monto_comision)
    SELECT v.vendedora_id, p_campana_id, n.id, v.ventas, n.porcentaje, round(v.ventas * n.porcentaje / 100, 2)
      FROM (SELECT vendedora_id, SUM(subtotal) AS ventas
              FROM pedido
             WHERE campana_id = p_campana_id AND estado NOT IN ('BORRADOR', 'CANCELADO')
             GROUP BY vendedora_id) v
      JOIN nivel_comision n
        ON v.ventas >= n.monto_minimo AND (n.monto_maximo IS NULL OR v.ventas <= n.monto_maximo);

    GET DIAGNOSTICS v_filas = ROW_COUNT;
    RETURN v_filas;
END;
$$;

CREATE FUNCTION fn_aprobar_comisiones(p_campana_id smallint) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_filas integer;
BEGIN
    UPDATE comision SET estado = 'APROBADA', aprobada_en = now()
     WHERE campana_id = p_campana_id AND estado = 'CALCULADA';
    GET DIAGNOSTICS v_filas = ROW_COUNT;

    INSERT INTO notificacion (usuario_id, tipo, mensaje)
    SELECT v.usuario_id, 'COMISION',
           format('Tu comisión de la campaña %s es RD$ %s.', c.codigo, to_char(m.monto_comision, 'FM999G999G990D00'))
      FROM comision m
      JOIN vendedora v ON v.id = m.vendedora_id
      JOIN campana c   ON c.id = m.campana_id
     WHERE m.campana_id = p_campana_id AND v.usuario_id IS NOT NULL;

    RETURN v_filas;
END;
$$;

