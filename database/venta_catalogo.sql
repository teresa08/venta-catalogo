-- CU035 Catálogo vigente con precio final y disponibilidad
CREATE VIEW v_catalogo_vigente AS
SELECT c.codigo                              AS campana,
       ci.pagina,
       p.id                                  AS producto_id,
       p.sku,
       p.nombre,
       p.descripcion,
       cat.nombre                            AS categoria,
       ci.precio,
       ci.precio_oferta,
       COALESCE(ci.precio_oferta, ci.precio) AS precio_final,
       ci.destacado,
       i.existencia - i.reservado            AS disponible
  FROM campana c
  JOIN catalogo_item ci ON ci.campana_id = c.id
  JOIN producto p       ON p.id = ci.producto_id AND p.activo
  JOIN categoria cat    ON cat.id = p.categoria_id AND cat.activa
  JOIN inventario i     ON i.producto_id = p.id
 WHERE c.estado = 'PUBLICADA';

-- CU050 Seguimiento del pedido
CREATE VIEW v_pedido_resumen AS
SELECT pe.id, pe.numero, c.codigo AS campana, v.codigo AS codigo_vendedora, v.nombre AS vendedora,
       cl.nombre AS cliente, pe.estado, pe.enviado_en, pe.subtotal, pe.itbis, pe.total,
       f.numero AS factura, d.mensajero, d.guia, d.fecha_entrega
  FROM pedido pe
  JOIN campana c     ON c.id = pe.campana_id
  JOIN vendedora v   ON v.id = pe.vendedora_id
  LEFT JOIN cliente cl  ON cl.id = pe.cliente_id
  LEFT JOIN factura f   ON f.pedido_id = pe.id AND f.estado = 'EMITIDA'
  LEFT JOIN despacho d  ON d.pedido_id = pe.id;

-- CU065 Estado de cuenta: cargos (facturas) y abonos (comisiones aprobadas y pagos)
CREATE VIEW v_estado_cuenta AS
SELECT pe.vendedora_id, f.fecha_emision AS fecha, 'Factura ' || f.numero AS concepto, f.total AS cargo, 0::numeric AS abono
  FROM factura f JOIN pedido pe ON pe.id = f.pedido_id
 WHERE f.estado = 'EMITIDA'
UNION ALL
SELECT m.vendedora_id, (c.fecha_fin + time '18:00')::timestamptz, format('Comisión %s (%s %%)', c.codigo, m.porcentaje), 0, m.monto_comision
  FROM comision m JOIN campana c ON c.id = m.campana_id
 WHERE m.estado IN ('APROBADA', 'PAGADA')
UNION ALL
SELECT pv.vendedora_id, (pv.fecha + time '12:00')::timestamptz, 'Pago: ' || pv.referencia, 0, pv.monto
  FROM pago_vendedora pv;

CREATE VIEW v_saldo_vendedora AS
SELECT v.id AS vendedora_id, v.codigo, v.nombre,
       COALESCE(SUM(ec.cargo), 0)                         AS cargos,
       COALESCE(SUM(ec.abono), 0)                         AS abonos,
       COALESCE(SUM(ec.cargo), 0) - COALESCE(SUM(ec.abono), 0) AS saldo
  FROM vendedora v
  LEFT JOIN v_estado_cuenta ec ON ec.vendedora_id = v.id
 GROUP BY v.id, v.codigo, v.nombre;

-- CU070 Existencias que requieren reposición
CREATE VIEW v_existencias_bajo_minimo AS
SELECT p.sku, p.nombre, i.existencia, i.reservado, i.existencia - i.reservado AS disponible, i.minimo
  FROM inventario i JOIN producto p ON p.id = i.producto_id
 WHERE p.activo AND i.existencia - i.reservado <= i.minimo
 ORDER BY i.existencia - i.reservado;

-- CU085 Reportes de ventas (montos sin ITBIS; excluye borradores y cancelados)
CREATE VIEW v_ventas_por_campana AS
SELECT c.id AS campana_id, c.codigo, c.nombre,
       COUNT(pe.id)                    AS pedidos,
       COALESCE(SUM(pe.subtotal), 0)   AS ventas,
       COALESCE(SUM(pe.itbis), 0)      AS itbis,
       COALESCE(ROUND(AVG(pe.subtotal), 2), 0) AS pedido_promedio
  FROM campana c
  LEFT JOIN pedido pe ON pe.campana_id = c.id AND pe.estado NOT IN ('BORRADOR', 'CANCELADO')
 GROUP BY c.id, c.codigo, c.nombre;

CREATE VIEW v_ventas_por_categoria AS
SELECT pe.campana_id, cat.nombre AS categoria, SUM(d.cantidad) AS unidades, SUM(d.importe) AS ventas
  FROM pedido pe
  JOIN pedido_detalle d ON d.pedido_id = pe.id
  JOIN producto p       ON p.id = d.producto_id
  JOIN categoria cat    ON cat.id = p.categoria_id
 WHERE pe.estado NOT IN ('BORRADOR', 'CANCELADO')
 GROUP BY pe.campana_id, cat.nombre;

CREATE VIEW v_ventas_por_vendedora AS
SELECT pe.campana_id, v.codigo, v.nombre, z.nombre AS zona, COUNT(*) AS pedidos, SUM(pe.subtotal) AS ventas
  FROM pedido pe
  JOIN vendedora v ON v.id = pe.vendedora_id
  JOIN zona z      ON z.id = v.zona_id
 WHERE pe.estado NOT IN ('BORRADOR', 'CANCELADO')
 GROUP BY pe.campana_id, v.codigo, v.nombre, z.nombre;

CREATE VIEW v_productos_mas_vendidos AS
SELECT pe.campana_id, p.sku, p.nombre, SUM(d.cantidad) AS unidades, SUM(d.importe) AS importe,
       RANK() OVER (PARTITION BY pe.campana_id ORDER BY SUM(d.importe) DESC) AS posicion
  FROM pedido pe
  JOIN pedido_detalle d ON d.pedido_id = pe.id
  JOIN producto p       ON p.id = d.producto_id
 WHERE pe.estado NOT IN ('BORRADOR', 'CANCELADO')
 GROUP BY pe.campana_id, p.sku, p.nombre;

