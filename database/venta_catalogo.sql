-- Tasa de ITBIS vigente (parámetro ITBIS, por defecto 18 %)
CREATE FUNCTION fn_tasa_itbis() RETURNS numeric
LANGUAGE sql STABLE AS $$
    SELECT COALESCE((SELECT valor::numeric FROM parametro WHERE clave = 'ITBIS'), 0.18);
$$;

-- Usuario que ejecuta la operación (la aplicación lo fija con set_config('app.usuario_id', ...))
CREATE FUNCTION fn_usuario_actual() RETURNS integer
LANGUAGE sql STABLE AS $$
    SELECT NULLIF(current_setting('app.usuario_id', true), '')::integer;
$$;

-- Mantiene la columna actualizado_en
CREATE FUNCTION trg_actualizado_en() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.actualizado_en := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_usuario_actualizado   BEFORE UPDATE ON usuario   FOR EACH ROW EXECUTE FUNCTION trg_actualizado_en();
CREATE TRIGGER tg_producto_actualizado  BEFORE UPDATE ON producto  FOR EACH ROW EXECUTE FUNCTION trg_actualizado_en();
CREATE TRIGGER tg_vendedora_actualizado BEFORE UPDATE ON vendedora FOR EACH ROW EXECUTE FUNCTION trg_actualizado_en();
CREATE TRIGGER tg_pedido_actualizado    BEFORE UPDATE ON pedido    FOR EACH ROW EXECUTE FUNCTION trg_actualizado_en();
CREATE TRIGGER tg_inventario_actualizado BEFORE UPDATE ON inventario FOR EACH ROW EXECUTE FUNCTION trg_actualizado_en();

-- Todo producto nuevo nace con su registro de inventario en cero
CREATE FUNCTION trg_producto_inventario() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO inventario (producto_id) VALUES (NEW.id) ON CONFLICT DO NOTHING;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_producto_inventario AFTER INSERT ON producto
    FOR EACH ROW EXECUTE FUNCTION trg_producto_inventario();

-- Recalcula subtotal, ITBIS y total del pedido cuando cambian sus líneas
CREATE FUNCTION trg_recalcular_pedido() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_pedido integer := COALESCE(NEW.pedido_id, OLD.pedido_id);
    v_sub    numeric(12,2);
BEGIN
    SELECT COALESCE(SUM(importe), 0) INTO v_sub FROM pedido_detalle WHERE pedido_id = v_pedido;
    UPDATE pedido
       SET subtotal = v_sub,
           itbis    = round(v_sub * fn_tasa_itbis(), 2),
           total    = v_sub + round(v_sub * fn_tasa_itbis(), 2)
     WHERE id = v_pedido;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tg_detalle_totales AFTER INSERT OR UPDATE OR DELETE ON pedido_detalle
    FOR EACH ROW EXECUTE FUNCTION trg_recalcular_pedido();

-- Las líneas solo se modifican mientras el pedido es un borrador (carrito)
CREATE FUNCTION trg_detalle_editable() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_estado varchar(12);
BEGIN
    SELECT estado INTO v_estado FROM pedido WHERE id = COALESCE(NEW.pedido_id, OLD.pedido_id);
    IF v_estado IS DISTINCT FROM 'BORRADOR' AND current_setting('app.carga_inicial', true) IS DISTINCT FROM 'on' THEN
        RAISE EXCEPTION 'El pedido ya fue enviado; sus líneas no se pueden modificar (estado %).', v_estado
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER tg_detalle_editable BEFORE INSERT OR UPDATE OR DELETE ON pedido_detalle
    FOR EACH ROW EXECUTE FUNCTION trg_detalle_editable();

-- Registra cada cambio de estado del pedido y avisa a la vendedora (CU050)
CREATE FUNCTION trg_pedido_estado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario_vendedora integer;
    v_texto varchar(40);
BEGIN
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        INSERT INTO pedido_historial (pedido_id, estado_anterior, estado_nuevo, usuario_id, nota)
        VALUES (NEW.id, OLD.estado, NEW.estado, fn_usuario_actual(), NULLIF(current_setting('app.nota', true), ''));

        SELECT usuario_id INTO v_usuario_vendedora FROM vendedora WHERE id = NEW.vendedora_id;
        IF v_usuario_vendedora IS NOT NULL AND NEW.estado <> 'ENVIADO' THEN
            v_texto := CASE NEW.estado
                           WHEN 'FACTURADO'   THEN 'fue facturado'
                           WHEN 'EN_DESPACHO' THEN 'salió con el mensajero'
                           WHEN 'ENTREGADO'   THEN 'fue entregado'
                           WHEN 'CANCELADO'   THEN 'fue cancelado'
                           ELSE lower(NEW.estado)
                       END;
            INSERT INTO notificacion (usuario_id, tipo, mensaje)
            VALUES (v_usuario_vendedora, 'PEDIDO', format('Tu pedido %s %s.', NEW.numero, v_texto));
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_pedido_estado AFTER UPDATE OF estado ON pedido
    FOR EACH ROW EXECUTE FUNCTION trg_pedido_estado();

